#!/usr/bin/env python3
"""
gen_descriptor.py -- the BLUR v36 body descriptor, generated from the MJCF.

The MJCF and blur_meta.json are ground truth for geometry, masses, joint
ranges, springs and torque limits. They are read, never edited. What the
MJCF does not contain (CAN node map, encoder placement, motor constants,
power, e-stop) is written down HERE, once, with where each number came
from, so a wrong assumption is a one-line fix in one file.

Outputs (both checked in, both regenerated by this script):
  blur/descriptor.json         read by the MuJoCo nerve bridge
  os/blur/src/gen.rs           read by brainos-blur (no_std)

Both carry the sha256 of blur.xml, and brainos-blur's tests fail if the
descriptor was generated from a different model than the one on disk.

  ../BLUR/blur_mujoco/.venv/bin/python blur/gen_descriptor.py
"""
import hashlib, json, math, os, sys

import mujoco
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
MJCF_DIR = os.environ.get('BLUR_MJCF_DIR',
                          os.path.expanduser('~/Desktop/Arenda_Projects/BLUR/blur_mujoco_v36'))

# ---------------------------------------------------------------- motors
# Output-side constants. kt_out = 60/(2*pi*KV) * gear * efficiency.
# V_SAG and the KVs are the ones physics_checks.py uses; the 4015 KV is
# marked there as an assumption and stays one here. Efficiency 0.85 is
# assumed for a 16:1 printed planetary; it reproduces the README's
# "~1 N*m per 10 A" for the 2806.5.
V_SAG = 20.0          # sagged 6S under load (physics_checks.py)
GEAR_EFF = 0.85       # ASSUMED
MOTORS = {
    'esc2806': dict(model='2806.5 1300KV + 16:1, B-G431B-ESC1 (FOC)', kv=1300, gear=16,
                    drv_peak_a=40.0, drv='B-G431B-ESC1',
                    drv_note='40 A peak is ASSUMED from the ESC1 product page; verify on load day',
                    kv_source='part number'),
    'gimbal4015': dict(model='4015 hollow gimbal + MT6701 + 16:1', kv=100, gear=16,
                       drv_peak_a=2.5, drv='SimpleFOC Mini (DRV8313) on an ESP32-S3 node -- ASSUMED, prompt does not name the 4015 driver',
                       drv_note='DRV8313 2.5 A peak per half-bridge',
                       kv_source='ASSUMED ~100 (physics_checks.py)'),
    'gimbal2204': dict(model='2204 260KV + 16:1', kv=260, gear=16,
                       drv_peak_a=2.5, drv='SimpleFOC Mini (DRV8313) on an ESP32-S3 node',
                       drv_note='DRV8313 2.5 A peak per half-bridge', kv_source='part number'),
    'winch2204': dict(model='2204 260KV winch, 5 mm drum', kv=260, gear=16,
                      drv_peak_a=2.5, drv='SimpleFOC Mini (DRV8313) on an ESP32-S3 node',
                      drv_note='DRV8313 2.5 A peak per half-bridge', kv_source='part number',
                      drum_m=0.005),
    'n20': dict(model='N20 6 V gearmotor + M3 lead screw', kv=None, gear=None,
                drv_peak_a=1.5, drv='DRV8833', drv_note='DRV8833 1.5 A rms per bridge', kv_source='n/a'),
}

def motor_of(kind):
    if '2806' in kind: return 'esc2806'
    if '4015' in kind: return 'gimbal4015'
    if 'winch' in kind: return 'winch2204'
    if '2204' in kind: return 'gimbal2204'
    if 'N20' in kind: return 'n20'
    raise ValueError(kind)

# ---------------------------------------------------------------- CAN map
# A PROPOSAL, not a wiring diagram. Teensy 4.1 has three CAN controllers;
# SN65HVD230 is a 1 Mbit/s transceiver, so all three run classic CAN at
# 1 Mbit/s. Bus A = front legs + head node, B = rear legs + rear node,
# C = the spine node alone. Node ids 0x01-0x0C are the ESC1s, 0x11-0x13
# the ESP32-S3 nodes. A node with several motors addresses them by slot.
BUSES = {'A': 'front: FR/FL ESC1 x6 + FRONT node', 'B': 'rear: RR/RL ESC1 x6 + REAR node',
         'C': 'spine: MID node'}
NODE_OF = {}
_esc = 1
for leg in ['FR', 'FL', 'RR', 'RL']:
    for j in ['pitch', 'knee', 'dist']:
        NODE_OF[f'{leg}_{j}'] = ('A' if leg[0] == 'F' else 'B', _esc, 0, 'esc1'); _esc += 1
for slot, n in enumerate(['FR_abd', 'FL_abd', 'neck_lift', 'neck_pan', 'neck_tilt', 'jaw']):
    NODE_OF[n] = ('A', 0x11, slot, 'esp32s3')
for slot, n in enumerate(['spine_s1', 'spine_twist', 'spine_s2']):
    NODE_OF[n] = ('C', 0x12, slot, 'esp32s3')
for slot, n in enumerate(['RR_abd', 'RL_abd', 'tail_winch_pitch', 'tail_winch_yaw', 'gripper']):
    NODE_OF[n] = ('B', 0x13, slot, 'esp32s3')
NODE_NAMES = {0x11: 'FRONT', 0x12: 'MID', 0x13: 'REAR'}

# ---------------------------------------------------------------- encoders
# MT6701, 14-bit absolute single-turn. "Built-in" on the 4015 means on the
# MOTOR, ahead of the 16:1 gearbox, so the output angle is known only
# modulo 2*pi/16 = 22.5 deg at power-on and must be resolved (homing or a
# rest-pose prior) every boot. The prompt says "MT6701 on every joint";
# for the 2806.5, 2204 and the winches that is read as joint-side.
# The N20 gripper has no encoder.
def encoder_of(motor):
    if motor == 'gimbal4015': return 'motor'
    if motor == 'n20': return 'none'
    return 'joint'

ENC_BITS = 14
JIG_HEIGHT = 0.30     # nerves.py --jig-height default: chest raised this far above the stand pose

def main():
    xml = os.path.join(MJCF_DIR, 'blur.xml')
    sha = hashlib.sha256(open(xml, 'rb').read()).hexdigest()
    meta = json.load(open(os.path.join(MJCF_DIR, 'blur_meta.json')))
    m = mujoco.MjModel.from_xml_path(os.path.join(MJCF_DIR, 'scene_flat.xml'))
    d = mujoco.MjData(m)
    key = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_KEY, 'stand')
    mujoco.mj_resetDataKeyframe(m, d, key); mujoco.mj_forward(m, d)

    acts = []
    for a in meta['actuators']:
        i = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_ACTUATOR, a['name'])
        assert i >= 0, a
        mk = motor_of(a['kind']); mo = MOTORS[mk]
        frc = float(m.actuator_forcerange[i, 1])
        if abs(frc - a['limit']) > 1e-6:
            sys.exit(f"MISMATCH {a['name']}: meta limit {a['limit']} vs MJCF forcerange {frc}")
        if a['tendon']:
            t = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_TENDON, a['target'])
            lo, hi = m.tendon_range[t] if m.tendon_limited[t] else (float('nan'), float('nan'))
            # a winch tendon length range from the joint ranges it spans
            adr, num = m.tendon_adr[t], m.tendon_num[t]
            lo = hi = 0.0
            for k in range(adr, adr + num):
                jr = m.jnt_range[m.wrap_objid[k]]; c = m.wrap_prm[k]
                lo += min(c * jr[0], c * jr[1]); hi += max(c * jr[0], c * jr[1])
            q_min, q_max, unit = lo, hi, 'm'
            q_stand = float(d.ten_length[t])
        else:
            j = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, a['target'])
            q_min, q_max = map(float, m.jnt_range[j]); unit = 'rad'
            q_stand = float(d.qpos[m.jnt_qposadr[j]])
        kp, kd = float(m.actuator_gainprm[i, 0]), float(-m.actuator_biasprm[i, 2])
        if mk in ('esc2806', 'gimbal4015', 'gimbal2204'):
            kt_out = 60 / (2 * math.pi * mo['kv']) * mo['gear'] * GEAR_EFF
            w0 = mo['kv'] * V_SAG / mo['gear'] * 2 * math.pi / 60
            i_needed = frc / kt_out
        elif mk == 'winch2204':
            kt_out = 60 / (2 * math.pi * mo['kv']) * mo['gear'] * GEAR_EFF / mo['drum_m']   # N per A
            w0 = mo['kv'] * V_SAG / mo['gear'] * 2 * math.pi / 60 * mo['drum_m']           # m/s
            i_needed = frc / kt_out
        else:
            kt_out, w0, i_needed = float('nan'), 0.5, float('nan')   # lead screw: ~0.5 rad/s finger, ASSUMED
        # which stop to home on: the one the passive load (gravity in the jig
        # pose + every spring) pushes the joint toward, so homing never
        # fights a spring it cannot beat under the capped current
        home_to = home_side(m, a)
        bus, node, slot, nk = NODE_OF[a['name']]
        acts.append(dict(
            name=a['name'], target=a['target'], tendon=bool(a['tendon']), motor=mk,
            tau_max=frc, unit=unit, q_min=q_min, q_max=q_max, q_stand=q_stand,
            kp_mjcf=kp, kd_mjcf=kd, kt_out=kt_out, w0=w0, i_for_tau_max=i_needed,
            drv_peak_a=mo['drv_peak_a'],
            current_ok=bool(not (i_needed == i_needed) or i_needed <= mo['drv_peak_a'] * 1.02),
            bus=bus, node=node, slot=slot, node_kind=nk, encoder=encoder_of(mk), home_to=home_to,
            gear=mo['gear'] or 1))

    springs = []
    for t in range(m.ntendon):
        k = float(m.tendon_stiffness[t])
        if k <= 0: continue
        name = mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_TENDON, t)
        kind = ('coilover' if name.startswith('coilover') else 'extension' if name.startswith('extspring')
                else 'tpu_knee_extensor' if name.startswith('knee_extensor') else 'jump' if name.startswith('jumpspring')
                else 'other')
        lo, hi = map(float, m.tendon_lengthspring[t])
        L = float(d.ten_length[t])
        stretch = max(0.0, lo - L) if L < lo else max(0.0, L - hi)
        springs.append(dict(name=name, kind=kind, stiffness=k, rest_lo=lo, rest_hi=hi,
                            tension_at_stand=k * stretch * (1 if L > hi else -1 if L < lo else 0)))
    passive = []
    for j in range(m.njnt):
        if m.jnt_stiffness[j] > 0:
            passive.append(dict(name=mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_JOINT, j),
                                stiffness=float(m.jnt_stiffness[j]), springref=float(m.qpos_spring[m.jnt_qposadr[j]]),
                                q_min=float(m.jnt_range[j, 0]), q_max=float(m.jnt_range[j, 1])))
    # the tail cables' zero reference: cable length with no winch force,
    # the body held in the stand pose with the chest level (the jig) and
    # the nine sprung segments hanging under gravity. The tail has no hard
    # stop to home on; this is the length the twin's physics predicts.
    rest = tail_rest_lengths(m)
    for a in acts:
        if a['tendon']:
            a['q_rest_stand'] = rest[a['target']]

    nodes = {}
    for a in acts:
        n = nodes.setdefault(a['node'], dict(id=a['node'], bus=a['bus'], kind=a['node_kind'],
                                             name=NODE_NAMES.get(a['node'], a['name']), slots=[]))
        n['slots'].append(a['name'])
    nodes = sorted(nodes.values(), key=lambda n: n['id'])

    desc = dict(
        generator='blur/gen_descriptor.py', mjcf_dir=MJCF_DIR, mjcf_sha256=sha,
        rig='v36', mass_kg=float(m.body_subtreemass[1]), nq=int(m.nq), nv=int(m.nv), nu=int(m.nu),
        timestep=float(m.opt.timestep), v_sag=V_SAG, gear_eff_assumed=GEAR_EFF, enc_bits=ENC_BITS,
        motors=MOTORS, buses=BUSES, actuators=acts, nodes=nodes, springs=springs, passive_joints=passive,
        sensors=dict(imu=dict(part='BMI270', site='imu', acc_range_g=8, gyro_range_dps=2000,
                              acc_lsb_per_g=4096, gyro_lsb_per_dps=16.384, on='Teensy 4.1 SPI'),
                     encoders='MT6701 14-bit, see actuators[].encoder', current='per-node phase current',
                     cameras='2 x Arducam Camera Module 3 Wide (not in the MJCF)',
                     audio='microphones + speaker (not in the MJCF)',
                     not_on_hardware=['FR_foot_touch', 'FL_foot_touch', 'RR_foot_touch', 'RL_foot_touch']),
        power=dict(pack='2 x 6S 1000 mAh 100C LiPo', v_nominal=22.2, v_full=25.2, v_sag=V_SAG,
                   v_cutoff=19.8, fuses='PDB', loop_key=True),
        estop=dict(kind='latching mushroom switch in series with the motor rail (cuts power; no software path closes it)',
                   can_broadcast_id=0x000),
        missing_from_mjcf=['spine ligament springs + TPU bump stops (prompt lists them; v36 MJCF has none)',
                           'motor torque/speed curves (MJCF has a flat forcerange; bridge applies a derate)',
                           'cameras, microphones, speaker'],
    )
    out_json = os.path.join(HERE, 'descriptor.json')
    json.dump(desc, open(out_json, 'w'), indent=1)
    write_rust(desc, os.path.join(REPO, 'os', 'blur', 'src', 'gen.rs'))
    print(f'wrote {out_json} and os/blur/src/gen.rs  (mjcf sha256 {sha[:16]}...)')
    for a in acts:
        if not a['current_ok']:
            print(f"  CURRENT: {a['name']} needs {a['i_for_tau_max']:.2f} A for {a['tau_max']} N*m, driver peak {a['drv_peak_a']} A")


def tail_rest_lengths(m):
    """Cable length at zero winch force, body held at the stand pose by
    torque (the MJCF's own position servos), chest clamped in the jig.
    Held by torque, not by overwriting joint angles: a kinematic hold of
    the joints injects motion the 40 g tail responds to (it sagged an
    unphysical 0.42 rad at the root that way)."""
    d = mujoco.MjData(m)
    key = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_KEY, 'stand')
    mujoco.mj_resetDataKeyframe(m, d, key)
    gp, bp = m.actuator_gainprm.copy(), m.actuator_biasprm.copy()
    for i in range(m.nu):
        if m.actuator_trntype[i] == mujoco.mjtTrn.mjTRN_TENDON:
            m.actuator_gainprm[i] = 0; m.actuator_biasprm[i] = 0     # the winches: no force
            d.ctrl[i] = 0
        else:
            j = int(m.actuator_trnid[i, 0])
            d.ctrl[i] = d.qpos[m.jnt_qposadr[j]]                     # the joints: hold stand
    d.qpos[2] += JIG_HEIGHT                                          # in the jig, tail clear of the floor
    root = d.qpos[:7].copy()
    acc, n = {}, 0
    T = 6.0
    for k in range(int(T / m.opt.timestep)):
        d.qpos[:7] = root; d.qvel[:6] = 0
        mujoco.mj_step(m, d)
        if k * m.opt.timestep >= T - 1.0:                            # average the last second
            for t in range(m.ntendon):
                acc[t] = acc.get(t, 0.0) + float(d.ten_length[t])
            n += 1
    m.actuator_gainprm[:] = gp; m.actuator_biasprm[:] = bp
    out = {}
    for t in range(m.ntendon):
        name = mujoco.mj_id2name(m, mujoco.mjtObj.mjOBJ_TENDON, t)
        if name.startswith('tail_'):
            out[name] = acc[t] / n
    return out


def home_side(m, a):
    """'low' or 'high': the stop the passive torque at the stand pose points to."""
    d = mujoco.MjData(m)
    key = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_KEY, 'stand')
    mujoco.mj_resetDataKeyframe(m, d, key)
    mujoco.mj_forward(m, d)
    # generalized passive force = springs (joint + tendon) - gravity/coriolis bias
    pas = d.qfrc_passive - d.qfrc_bias
    if a['tendon']:
        t = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_TENDON, a['target'])
        adr, num = m.tendon_adr[t], m.tendon_num[t]    # a fixed tendon: sum of coef x joint torque
        f = sum(float(m.wrap_prm[k]) * float(pas[m.jnt_dofadr[m.wrap_objid[k]]]) for k in range(adr, adr + num))
    else:
        j = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_JOINT, a['target'])
        f = float(pas[m.jnt_dofadr[j]])
    return 'low' if f <= 0 else 'high'


def f(x):
    if x != x: return 'f32::NAN'
    s = repr(float(x))
    return s if ('.' in s or 'e' in s) else s + '.0'


def write_rust(desc, path):
    MK = dict(esc2806='Esc2806', gimbal4015='Gimbal4015', gimbal2204='Gimbal2204', winch2204='Winch2204', n20='N20')
    EN = dict(joint='Joint', motor='Motor', none='None')
    L = ['//! GENERATED by blur/gen_descriptor.py from the v36 MJCF. Do not edit;',
         '//! change the generator and rerun it. `tests` checks the sha256 below',
         '//! against the model on disk.', '',
         'use crate::descriptor::{ActuatorSpec, Bus, EncoderSide, MotorKind, NodeKind, NodeSpec, PassiveJoint, SpringKind, SpringSpec};', '',
         f'pub const MJCF_SHA256: &str = "{desc["mjcf_sha256"]}";',
         f'pub const MASS_KG: f32 = {f(desc["mass_kg"])};',
         f'pub const V_SAG: f32 = {f(desc["v_sag"])};', '',
         f'pub static ACTUATORS: [ActuatorSpec; {len(desc["actuators"])}] = [']
    for a in desc['actuators']:
        L.append(f'    ActuatorSpec {{ name: "{a["name"]}", motor: MotorKind::{MK[a["motor"]]}, tendon: {str(a["tendon"]).lower()}, '
                 f'tau_max: {f(a["tau_max"])}, q_min: {f(a["q_min"])}, q_max: {f(a["q_max"])}, q_stand: {f(a["q_stand"])}, '
                 f'kt_out: {f(a["kt_out"])}, w0: {f(a["w0"])}, drv_peak_a: {f(a["drv_peak_a"])}, gear: {f(a["gear"])}, '
                 f'bus: Bus::{a["bus"]}, node: {a["node"]}, slot: {a["slot"]}, encoder: EncoderSide::{EN[a["encoder"]]}, '
                 f'home_high: {"true" if a["home_to"] == "high" else "false"}, q_rest: {f(a.get("q_rest_stand", float("nan")))} }},')
    L += ['];', '', f'pub static NODES: [NodeSpec; {len(desc["nodes"])}] = [']
    for n in desc['nodes']:
        L.append(f'    NodeSpec {{ id: {n["id"]}, bus: Bus::{n["bus"]}, kind: NodeKind::{"Esc1" if n["kind"] == "esc1" else "Esp32S3"}, '
                 f'name: "{n["name"]}", slots: {len(n["slots"])} }},')
    SK = dict(coilover='Coilover', extension='Extension', tpu_knee_extensor='TpuKneeExtensor', jump='Jump', other='Other')
    L += ['];', '', f'pub static SPRINGS: [SpringSpec; {len(desc["springs"])}] = [']
    for s in desc['springs']:
        L.append(f'    SpringSpec {{ name: "{s["name"]}", kind: SpringKind::{SK[s["kind"]]}, stiffness: {f(s["stiffness"])}, '
                 f'rest_lo: {f(max(s["rest_lo"], -1e30))}, rest_hi: {f(s["rest_hi"])} }},')
    L += ['];', '', f'pub static PASSIVE_JOINTS: [PassiveJoint; {len(desc["passive_joints"])}] = [']
    for p in desc['passive_joints']:
        L.append(f'    PassiveJoint {{ name: "{p["name"]}", stiffness: {f(p["stiffness"])}, springref: {f(p["springref"])}, '
                 f'q_min: {f(p["q_min"])}, q_max: {f(p["q_max"])} }},')
    L += ['];', '']
    open(path, 'w').write('\n'.join(L))


if __name__ == '__main__':
    main()
