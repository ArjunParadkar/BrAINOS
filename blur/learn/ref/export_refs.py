#!/usr/bin/env python3
"""export_refs.py -- the keyframe references the reflexes were trained around,
as Rust constants for the Teensy (os/blur/src/refs_gen.rs), plus a sample
table (ref/ref_samples.txt) the Rust parity test checks ref(t) against."""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.dirname(HERE))
import numpy as np
import env as E, skills as S

refs = {'STANDUP': S.STANDUP_REF}
R = S.load_righting()
for c in ('left', 'right', 'back'):
    refs['RIGHTING_' + c.upper()] = R[c]
out = ['//! Generated by blur/learn/ref/export_refs.py -- do not edit. The keyframe',
       '//! references the get-up reflexes were trained around (min-jerk between keys).',
       'use crate::descriptor::N_ACT;', '']
for name, ref in refs.items():
    out.append(f'pub const {name}: &[(f32, [f32; N_ACT])] = &[')
    for t, q in ref.keys:
        out.append(f'    ({float(t)!r}, [' + ', '.join(f'{float(v)!r}' for v in q) + ']),')
    out.append('];')
open(os.path.join(HERE, '..', '..', '..', 'os', 'blur', 'src', 'refs_gen.rs'), 'w').write('\n'.join(out) + '\n')
with open(os.path.join(HERE, 'ref_samples.txt'), 'w') as f:
    f.write('# name t q[26]  (ref(t) from keyframes.Reference)\n')
    for name, ref in refs.items():
        for t in np.linspace(0, ref.T + 0.5, 23):
            f.write(name + ' ' + repr(float(t)) + ' ' + ' '.join(repr(float(v)) for v in ref(t)) + '\n')
print('wrote', list(refs))
