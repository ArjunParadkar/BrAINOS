#!/usr/bin/env python3
"""Generate the BPU mock's lookup tables and golden vectors from the reference.

The reference is bpusim/fixed.py ("This module IS the contract"), the same
integer model the KV260 FPGA tile was checked against. This script only
*reads* that repository. It writes two things here:

  src/tables_gen.rs        the five 1024-entry tables the contract defines by
                           formula (Gaussian inverse CDF; device step and
                           cumulative-pulse tables), as Rust constants
  tests/golden/*.txt       inputs and the reference's outputs, for
                           tests/golden.rs to reproduce bit for bit

Usage:  tools/gen_golden.py [path-to-bpusim-repo]
        (default: ../../../bpusim relative to the brainos repo)

Re-running it must reproduce the committed files exactly; tests/golden.rs
records the reference's git commit so a change in the contract is visible.
"""
import pathlib, subprocess, sys
import numpy as np

here = pathlib.Path(__file__).resolve().parent.parent
repo = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else here.parents[2] / "bpusim"
sys.path.insert(0, str(repo))
sys.path.insert(0, str(repo / "fpga" / "vectors"))
from bpusim import fixed as F          # noqa: E402
import gen_vectors as GV               # noqa: E402

commit = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
dirty = subprocess.run(["git", "-C", str(repo), "status", "--porcelain", "bpusim/fixed.py", "fpga/vectors/gen_vectors.py"],
                       capture_output=True, text=True).stdout.strip()
ref = f"bpusim {commit[:12]}{' (fixed.py modified)' if dirty else ''}"

def ints(a):
    return " ".join(str(int(v)) for v in np.asarray(a).reshape(-1))

# ----------------------------------------------------------------- tables
t = F.tables()
def rust_table(name, ty, arr):
    body = ",\n    ".join(", ".join(str(int(v)) for v in arr[i:i + 12]) for i in range(0, len(arr), 12))
    return f"pub static {name}: [{ty}; {len(arr)}] = [\n    {body},\n];\n"

src = f"""// GENERATED by tools/gen_golden.py from {ref}. Do not edit.
//
// The contract defines these tables by formula (bpusim/fixed.py:
// gaussian_lut, device_tables). They are stored rather than computed
// because computing them needs exp() and the inverse normal CDF, and a
// table the mock computes with its own floating point would be a table
// that can differ from the reference in its last bit.

/// Gaussian inverse CDF: rne(Phi^-1((k + 0.5) / 1024) * 2^13), Q3.13.
{rust_table("ZLUT", "i16", F.zlut())}
/// Potentiation step: rne(0.05 * exp(-3 w) * 2^15), w = (k + 0.5) / 1024.
{rust_table("STEP_UP", "i32", t["STEP_UP"])}
/// Depression step: rne(0.05 * exp(-3 (1 - w)) * 2^15).
{rust_table("STEP_DN", "i32", t["STEP_DN"])}
/// Cumulative potentiation pulse index, Q.8.
{rust_table("NUP", "i32", t["NUP"])}
/// Cumulative depression pulse index, Q.8.
{rust_table("NDN", "i32", t["NDN"])}"""
(here / "src" / "tables_gen.rs").write_text(src)

gold = here / "tests" / "golden"
gold.mkdir(parents=True, exist_ok=True)
(gold / "REFERENCE.txt").write_text(ref + "\n")

# ----------------------------------------------------------------- tile reads
# The FPGA gate's own vectors: seeds 0..47 (one and two passes, five noise
# levels, three ADC ranges, masked tiles) plus every contract corner case.
lines = []
vecs = [GV.make_vector(s) for s in range(48)] + GV.corner_vectors()
for v in vecs:
    lines.append(f"V {v['passes']} {v['S']}")
    lines.append("wp " + ints(v["wp"]))
    lines.append("wm " + ints(v["wm"]))
    lines.append("mask " + ints(np.asarray(v["mask"]).astype(int)))
    lines.append("x " + ints(v["x"]))
    lines.append("eta " + ints(v["eta"]))
    lines.append("y " + ints(v["y"]))
    lines.append("Y " + ints(v["Y"]))
    lines.append(f"clipped {v['clipped']}")
(gold / "tile_read.txt").write_text("\n".join(lines) + "\n")
n_two = sum(1 for v in vecs if v["passes"] == 2)

# ----------------------------------------------------------------- noise generator (mode B)
lines = []
for seed, sigma in [(0, 0.05), (1, 0.005), (0xDEADBEEFCAFEF00D, 0.2), (42, 0.0), (7, 0.1)]:
    sq = F.sigma_to_code(sigma)
    p = F.EtaPRNG(seed, sq)
    lines.append(f"P {seed} {sq}")
    lines.append("b0 " + ints(p.read_block()))
    lines.append("b1 " + ints(p.read_block()))
(gold / "prng.txt").write_text("\n".join(lines) + "\n")

# ----------------------------------------------------------------- write path, function by function
rng = np.random.default_rng(2026)
lines = []
ws = rng.integers(0, F.WS_ONE + 1, 400)
ws[:4] = [0, 1, F.WS_ONE - 1, F.WS_ONE]
lines.append("ws " + ints(ws))
lines.append("ws_to_wq " + ints(F.ws_to_wq(ws)))
gain = rng.integers(F.GAIN_MIN, 2 * F.GAIN_ONE, 400)
c2c = rng.integers(-F.ETA_MAX, F.ETA_MAX + 1, 400)
lines.append("gain " + ints(gain))
lines.append("c2c " + ints(c2c))
lines.append("step_up " + ints(F.step_q(ws, gain, c2c, np.ones(400, np.int64))))
lines.append("step_dn " + ints(F.step_q(ws, gain, c2c, -np.ones(400, np.int64))))
tgt = rng.integers(0, F.WS_ONE + 1, 400)
lines.append("tgt " + ints(tgt))
lines.append("pulses_for " + ints(F.pulses_for(ws, tgt)))
gsum = rng.integers(0, 8 * 64 * 140000, 400)
gsum[:3] = [0, 8 * 64 * F.GMIN_Q, 8 * 64 * F.GMAX_Q]
lines.append("gsum " + ints(gsum))
lines.append("w_meas " + ints(F.w_meas_from_sum(gsum)))
xs = rng.integers(-(1 << 39), 1 << 39, 400)
xs[:6] = [0, 1, -1, 3 << 4, -(3 << 4), 5 << 4]
lines.append("rne_x " + ints(xs))
for s in (0, 1, 5, 17, 31):
    lines.append(f"rne_shift {s} " + ints(F.rne_shift(xs, s)))
# pulses applied one at a time, with a c2c sample per device per pulse round
n = rng.integers(-12, 13, 400)
dead = rng.random(400) < 0.05
state = {"k": 0}
def c2c_fn(shape):
    r = np.random.default_rng(1000 + state["k"]); state["k"] += 1
    return r.integers(-2000, 2001, shape)
lines.append("n " + ints(n))
lines.append("dead " + ints(dead.astype(int)))
state["k"] = 0
rounds = []
def c2c_rec(shape):
    a = c2c_fn(shape); rounds.append(a); return a
out = F.pulse(ws, n, gain, c2c_rec, dead)
lines.append(f"c2c_rounds {len(rounds)}")
for a in rounds:
    lines.append("c2c_round " + ints(a))
lines.append("pulse " + ints(out))
(gold / "write_path.txt").write_text("\n".join(lines) + "\n")

# ----------------------------------------------------------------- write-verify, whole procedure
# The harness both sides implement (it is not part of the contract; the
# contract takes read_fn and c2c_fn as parameters):
#   noise  one xoshiro128** seeded prng_seed_words(seed, 0); each sample is
#          eta = clamp((sigma_q * ZLUT[word >> 22] + 2^12) >> 13)
#   read   VERIFY_READS reads; in each, devices in index order; every device
#          contributes noisy_conductance(conductance(ws_to_wq(w)), eta) * 64
#   c2c    zero
def program(seed, sigma, w0, tgt, gain, dead):
    g = F.Xoshiro128ss(*F.prng_seed_words(seed, 0)); lut = F.zlut(); sq = F.sigma_to_code(sigma)
    def eta():
        z = int(lut[g.next() >> 22]); e = (sq * z + 4096) >> 13
        return max(-F.ETA_MAX, min(F.ETA_MAX, e))
    def read_fn(w):
        gq = F.conductance_q(F.ws_to_wq(w)); s = np.zeros(len(w), np.int64)
        for _ in range(F.VERIFY_READS):
            for i in range(len(w)):
                s[i] += int(F.noisy_conductance_q(gq[i], eta())) * F.VERIFY_CODE
        return s
    return F.program_target(w0, tgt, gain, read_fn, lambda shape: np.zeros(shape, np.int64), dead)

lines = []
for case, (seed, sigma) in enumerate([(11, 0.0), (12, 0.005), (13, 0.02), (14, 0.05), (15, 0.2)]):
    r = np.random.default_rng(500 + case)
    N = 96
    w0 = r.integers(0, F.WS_ONE + 1, N) if case % 2 else np.zeros(N, np.int64)
    tg = r.integers(0, F.WS_ONE + 1, N)
    gn = r.integers(F.GAIN_MIN, 2 * F.GAIN_ONE, N) if case >= 2 else np.full(N, F.GAIN_ONE)
    dd = (r.random(N) < 0.04) if case >= 3 else np.zeros(N, bool)
    w, iters, total = program(seed, sigma, w0, tg, gn, dd)
    lines += [f"W {seed} {F.sigma_to_code(sigma)}", "w0 " + ints(w0), "tgt " + ints(tg), "gain " + ints(gn),
              "dead " + ints(dd.astype(int)), "w " + ints(w), f"iters {iters}", f"total {total}"]
(gold / "program_target.txt").write_text("\n".join(lines) + "\n")
print(f"reference: {ref}")
print(f"tile_read: {len(vecs)} vectors ({len(vecs) - n_two} one-pass, {n_two} two-pass); prng: 5 seeds; "
      f"write path: 400-device arrays; program_target: 5 runs")
